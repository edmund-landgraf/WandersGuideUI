CREATE TABLE IF NOT EXISTS pf2e_formula_entries (
  formula_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wg_item_id bigint NOT NULL,
  formula_name text NOT NULL,
  foundry_pack_id text NOT NULL,
  pf2e_slug text NOT NULL,
  foundry_document_id text NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  source_ref text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (wg_item_id, pf2e_slug)
);

CREATE INDEX IF NOT EXISTS pf2e_formula_entries_wg_item_id_idx
  ON pf2e_formula_entries (wg_item_id);

CREATE INDEX IF NOT EXISTS pf2e_formula_entries_active_name_idx
  ON pf2e_formula_entries (formula_name)
  WHERE status = 'active';
